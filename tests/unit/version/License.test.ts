describe('License — the MIT edition (D13)', () => {
  it('names itself MIT (java:66-68)', () => {
    expect(License.getCurrent().toString()).toBe('MIT');
    expect(String(License.getCurrent())).toBe('MIT');
  });

  it('mirrors the oracle build: no stats, a bundled GraphViz archive', () => {
    expect(ORACLE_BUILD).toEqual({ enableStats: false, isThereArchive: true });
  });
});

describe('License — the jar license page lines (NONE licence)', () => {
  const license = License.getCurrent();

  it('getText1 is the free edition header (java:114-119)', () => {
    expect(license.getText1(LicenseInfo.NONE)).toEqual(TEXT1_FREE);
  });

  it('getText2 carries the qrcode line, then the MIT, sponsor, images, archive and credits text', () => {
    expect(license.getText2(LicenseInfo.NONE)).toEqual([
      ...HEADER2,
      ...SUPPORT_US,
      QRCODES,
      ...MIT,
      ...SPONSORED,
      ...IMAGES,
      ...ARCHIVE,
      ...CREDITS,
    ]);
  });

  it('is 71 lines (the GPL jar page has 62: 13 GPL lines out, 22 addMit lines in), qrcode line at index 15', () => {
    const all = [...license.getText1(LicenseInfo.NONE), ...license.getText2(LicenseInfo.NONE)];
    expect(all).toHaveLength(71);
    expect(all.indexOf(QRCODES)).toBe(15);
  });

  it('getTextFull replaces the qrcode line by "" and " " (java:147-150)', () => {
    expect(license.getTextFull()).toEqual([
      ...TEXT1_FREE,
      ...HEADER2,
      ...SUPPORT_US,
      '',
      ' ',
      ...MIT,
      ...SPONSORED,
      ...IMAGES,
      ...ARCHIVE,
      ...CREDITS,
    ]);
  });
});

describe('License — the switches end3 reads (java:211-223)', () => {
  it('adds the statistics notice when stats are enabled', () => {
    const text = new License({ enableStats: true, isThereArchive: true }).getText2(LicenseInfo.NONE);
    const at = text.indexOf('by the very same license.');
    expect(text.slice(at + 1, at + 5)).toEqual([
      ' ',
      'This version of PlantUML records general local statistics about usage.',
      '(more info on https://plantuml.com/statistics-report)',
      ' ',
    ]);
  });

  it('prints the IGY notice without a bundled archive', () => {
    const text = new License({ enableStats: false, isThereArchive: false }).getText2(LicenseInfo.NONE);
    const at = text.indexOf('(see https://plantuml.com/graphviz-dot )');
    expect(text.slice(at - 2, at)).toEqual([
      'This is the IGY distribution (Install GraphViz by Yourself).',
      'You have to install GraphViz and to setup the GRAPHVIZ_DOT environment variable',
    ]);
  });
});

describe('License — a licensed build (java:120-128, :373-389)', () => {
  const license = License.getCurrent();

  it('NAMED: professional header, owner and expiration date', () => {
    expect(license.getText1(info(LicenseType.NAMED, EXPIRY))).toEqual([
      RULE,
      '| ',
      '|      PlantUML Professional Edition',
      '| ',
      RULE,
      '| ',
      '|      LICENSED TO : ACME',
      '|      EXPIRATION DATE : Oct 13, 2026',
      '|  ',
      RULE,
    ]);
  });

  it('DISTRIBUTOR: distributor line, then the expiry warning once expired', () => {
    expect(license.getText1(info(LicenseType.DISTRIBUTOR, EXPIRY + 1)).slice(5)).toEqual([
      '|  ',
      '|      DISTRIBUTED BY : ACME',
      '|  ',
      '|      <i>Warning: Your license has expired.',
      '|  ',
      RULE,
    ]);
  });

  it('prints a missing owner as Java string concatenation does: null (java:376, :382)', () => {
    const named: string[] = [];
    License.addLicenseInfo(named, info(LicenseType.NAMED, EXPIRY + 1, { name: undefined }));
    expect(named).toEqual(['| ', '|      LICENSED TO : null', '|      EXPIRATION DATE : Oct 13, 2026', '|  ']);
    const distributor: string[] = [];
    License.addLicenseInfo(distributor, info(LicenseType.DISTRIBUTOR, EXPIRY + 1, { name: undefined }));
    expect(distributor).toEqual(['|  ', '|      DISTRIBUTED BY : null', '|  ']);
  });

  it('UNKNOWN: no type line and no expiry warning', () => {
    expect(license.getText1(info(LicenseType.UNKNOWN, EXPIRY + 1)).slice(5)).toEqual([RULE]);
  });

  it('a valid licence drops the support, qrcode and sponsor lines', () => {
    expect(license.getText2(info(LicenseType.NAMED, EXPIRY))).toEqual([
      ...HEADER2,
      ...MIT,
      ...IMAGES,
      ...ARCHIVE,
      ...CREDITS,
    ]);
  });
});


const EXPIRY = Date.UTC(2026, 9, 13);

function info(
  type: LicenseType,
  now: number,
  owner: { readonly name: string | undefined } = { name: 'ACME' },
): LicenseInfo {
  const fields: LicenseInfoFields = {
    type,
    generationDate: 0,
    expirationDate: EXPIRY,
    owner: owner.name,
    context: undefined,
    sha: undefined,
    currentTimeMillis: () => now,
  };
  return new LicenseInfo(fields);
}


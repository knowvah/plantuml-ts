// ---------------------------------------------------------------- pure seams

/** `new TreeSet<>(values)` iteration order: `String.compareTo` is a UTF-16
 *  code-unit comparison, which is exactly JS `<` on strings. */
export function javaTreeSetOrder(values: Iterable<string>): string[] {
  return [...new Set(values)].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

/** `PSystemListArchimateSprites.java:67-72`: keep `.png`/`.svg`, name =
 *  `substring(0, len - 4)`, format = `substring(len - 3)`. */
export function archimateSpriteNames(folder: string, files: Iterable<string>): ArchimateSpriteName[] {
  return javaTreeSetOrder(files)
    .filter((file) => file.endsWith('.png') || file.endsWith('.svg'))
    .map((file) => ({ folder, name: file.slice(0, -4), format: file.slice(-3) as 'png' | 'svg' }));
}

/** `BufferedReader.readLine` loop: `\n`, `\r\n` or `\r` ends a line; a final
 *  terminator does not start an extra empty line. */
export function readLines(text: string): string[] {
  const lines = text.split(LINE_TERMINATOR);
  if (lines.at(-1) === '') lines.pop();
  return lines;
}

/** The concatenated string literals of `name = "..." + "...";` in a Java source. */
export function extractJavaStringConstant(java: string, name: string): string {
  const match = new RegExp(`\\b${name}\\s*=\\s*([^;]*);`).exec(java);
  if (match === null) throw new Error(`Java constant ${name} not found`);
  return [...match[1]!.matchAll(JAVA_STRING_LITERAL)].map((literal) => literal[1]).join('');
}

/** `PSystemDonors.java:158-165`: AsciiEncoder -> Brotli -> UTF-8 ->
 *  `replace('*', '.')` -> `StringTokenizer(s, "\n")` (empty tokens skipped). */
export function decodeDonors(encoded: string): string[] {
  const brotli = new AsciiEncoder().decode(encoded);
  const text = new TextDecoder().decode(brotliDecompressSync(brotli)).replaceAll('*', '.');
  return text.split('\n').filter((token) => token.length > 0);
}

const XML_ENTITIES: Readonly<Record<string, string>> = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'" };

function unescapeXml(text: string): string {
  return text.replace(/&(#x[0-9a-f]+|#[0-9]+|[a-z]+);/gi, (whole, entity: string) => {
    if (entity.startsWith('#x')) return String.fromCodePoint(parseInt(entity.slice(2), 16));
    if (entity.startsWith('#')) return String.fromCodePoint(parseInt(entity.slice(1), 10));
    return XML_ENTITIES[entity] ?? whole;
  });
}

/** Every `<text>` body of an oracle SVG, document order, XML-unescaped. */
export function svgTexts(svg: string): string[] {
  return [...svg.matchAll(SVG_TEXT)].map((match) => unescapeXml(match[1]!));
}

/** The one `<image ... xlink:href="data:image/png;base64,...">` of an oracle SVG. */
export function svgImage(svg: string): EmbeddedPng {
  const match = SVG_PNG_IMAGE.exec(svg);
  if (match === null) throw new Error('oracle SVG has no embedded PNG');
  return { png: match[3]!, width: Number(match[1]), height: Number(match[2]) };
}

/** Width/height from a PNG's IHDR chunk (big-endian, bytes 16..23). */
export function pngSize(bytes: Uint8Array): { width: number; height: number } {
  if (bytes.length < 24 || PNG_SIGNATURE.some((value, i) => bytes[i] !== value)) throw new Error('not a PNG');
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  return { width: view.getUint32(16), height: view.getUint32(20) };
}

type ManifestBundle = StdlibManifest['bundles'][string];

/** `Stdlib.retrieve` follows `link` to the folder whose info it reports (`Stdlib.java:166-176`). */
function resolveStdlibLink(bundles: ReadonlyMap<string, ManifestBundle>, name: string): StdlibCatalogEntry {
  let current = bundles.get(name);
  for (let hops = 0; current?.link !== undefined && hops < bundles.size; hops++)
    current = bundles.get(current.link.toLowerCase());
  if (current?.version === undefined || current.source === undefined)
    throw new Error(`stdlib bundle "${name}" has no version/source after following its links`);
  return { name, version: current.version, source: current.source };
}

/** `Stdlib.addInfoVersion(strings, true)` data: folder names from
 *  `home.spm` (lowercase, `TreeSet`, `Stdlib.java:204-211`), each with the
 *  version/source of the folder it links to. */
export function stdlibCatalog(manifest: StdlibManifest): StdlibCatalogEntry[] {
  const bundles = new Map(Object.entries(manifest.bundles).map(([key, value]) => [key.toLowerCase(), value]));
  return javaTreeSetOrder(bundles.keys()).map((name) => resolveStdlibLink(bundles, name));
}

/** `DedicationSimple.same` (java:67-71): letters and digits only, case-insensitive. */
export function sameDedication(sentence: string, line: string): boolean {
  const strip = (text: string): string => text.replace(/[^\p{L}0-9]+/gu, '').toLowerCase();
  return strip(sentence) === strip(line);
}

/** A source line `Dedications.get` accepts for `sentence`: sentences of 25
 *  chars or fewer are padded with `!`, which `same` strips. */
export function dedicationInputLine(sentence: string): string {
  if (sentence.length > DEDICATION_MIN_LENGTH) return sentence;
  return `${sentence} ${'!'.repeat(DEDICATION_MIN_LENGTH - sentence.length)}`;
}

// ------------------------------------------------------------------ emitters

async function prettify(path: string, source: string): Promise<string> {
  const config = await resolveConfig(join(REPO, path));
  return format(source, { ...config, filepath: join(REPO, path) });
}

function doc(lines: readonly string[]): string {
  return `/**\n${lines.map((line) => (line === '' ? ' *' : ` * ${line}`)).join('\n')}\n */\n`;
}

function stringList(name: string, what: string, values: readonly string[]): string {
  return `/** The ${values.length} ${what}. */\nexport const ${name}: readonly string[] = ${JSON.stringify(values)};\n`;
}

function inlineObjects(values: readonly object[]): string {
  const rows = values.map((value) => {
    const fields = Object.entries(value).map(([key, field]) => `${key}: ${JSON.stringify(field)}`);
    return `  { ${fields.join(', ')} },`;
  });
  return `[\n${rows.join('\n')}\n]`;
}


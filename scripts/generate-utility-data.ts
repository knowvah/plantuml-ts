/** The five list modules, path -> formatted source. */
export async function emitModules(data: GeneratedData): Promise<Map<string, string>> {
  const sources: [string, string][] = [
    [OUTPUT.openiconicAll, openiconicSource(data.openiconicAll)],
    [OUTPUT.archimateSpriteNames, archimateSource(data.archimateSpriteNames)],
    [OUTPUT.skinparameterNames, skinparameterSource(data.skinparameterNames)],
    [OUTPUT.donors, donorsSource(data.donors)],
    [OUTPUT.stdlibCatalog, stdlibSource(data.stdlibCatalog)],
  ];
  const result = new Map<string, string>();
  for (const [path, source] of sources) result.set(path, await prettify(path, source));
  return result;
}


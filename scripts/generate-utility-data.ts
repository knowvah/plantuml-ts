/**
 * Provenance generator for the utility-factory data modules (ufp T0e, D4/D5).
 *
 * Upstream reads these at runtime from its classpath or computes them from enums; a
 * browser-safe port has neither, so each is generated ONCE (each module's header names its
 * upstream source) and checked in:
 *
 *  1. `openiconic/all.txt`, file order (`PSystemListOpenIconic.java:66-79`), checked against
 *     `RAW_GLYPHS` -> `src/diagrams/openiconic/openiconic-all.ts`.
 *  2. `sprites/<folder>/*.{png,svg}` in `ResourcesUtils.getJarFile` (`TreeSet`) order, split as
 *     `PSystemListArchimateSprites.java:64-73` does, checked against the jar `listsprite`
 *     render -> `src/core/klimt/sprite/archimate-sprite-names.ts`.
 *  3. `SkinParam.getPossibleValues()` (`SkinParam.java:567-641`), partly enum-computed at
 *     runtime, so read off the jar `skinparameters` render -> `src/diagrams/donors/skinparameter-names.ts`.
 *  4. `PSystemDonors.DONORS`, decoded as java:156-170 does -> `src/diagrams/donors/donors-list.ts`.
 *  5. The bare `stdlib` page (`Stdlib.addInfoVersion`, `Stdlib.java:320-331`, reads the stdlib at
 *     runtime): from the vendored `assets/stdlib.manifest.json`, checked against the jar `stdlib`
 *     render -> `src/diagrams/version/stdlib-catalog.ts`.
 *  6. The PNGs the jar embeds for `charlie` (inline, `src/diagrams/eggs/charlie-image.ts`) and the
 *     10 `DedicationSimple` sentences (`Dedications.java:55-65`; bytes in
 *     `assets/dedication/<resource>.png`, outside the core bundle per stop 12, indexed by
 *     `src/diagrams/dedication/dedication-images.ts`).
 *
 * Byte-stable (no timestamps or host paths; repo prettier config). Oracles render only via
 * `scripts/oracle-render.sh`, into a temp dir outside the repo. The row types are imported
 * from the generated modules, which declare them (type-only: erased at run time).
 *
 * Usage: npx jiti scripts/generate-utility-data.ts [--plantuml <checkout>]
 */


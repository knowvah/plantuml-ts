// ------------------------------------------------------------------------ IO

function renderOracles(pumls: ReadonlyMap<string, string>): Map<string, string> {
  const scratch = mkdtempSync(join(tmpdir(), 'ufp-utility-data-'));
  try {
    const files = [...pumls].map(([name, line]) => {
      const file = join(scratch, `${name}.puml`);
      writeFileSync(file, `@startuml\n${line}\n@enduml\n`);
      return file;
    });
    execFileSync(join(REPO, 'scripts/oracle-render.sh'), [join(scratch, 'out'), ...files], { stdio: 'inherit' });
    return new Map([...pumls.keys()].map((name) => [name, readFileSync(join(scratch, 'out', `${name}.svg`), 'utf8')]));
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}

function oraclePumls(): Map<string, string> {
  const pumls = new Map([
    ['skinparameters', 'skinparameters'],
    ['listsprite', 'listsprite'],
    ['stdlib', 'stdlib'],
    ['charlie', 'charlie'],
  ]);
  for (const [resource, sentence] of DEDICATION_SENTENCES)
    pumls.set(`dedication-${resource}`, dedicationInputLine(sentence));
  return pumls;
}

function check(ok: boolean, message: string): void {
  if (!ok) throw new Error(`generate-utility-data: ${message}`);
}

function readArchimate(plantuml: string, listsprite: string): ArchimateSpriteName[] {
  const root = join(plantuml, 'src/main/resources/sprites');
  const folders = javaTreeSetOrder(readdirSync(root).filter((name) => statSync(join(root, name)).isDirectory()));
  const result = folders.flatMap((folder) => archimateSpriteNames(folder, readdirSync(join(root, folder))));
  const listed = svgTexts(listsprite).filter((text) => / \((png|svg)\)$/.test(text));
  check(
    JSON.stringify(listed) === JSON.stringify(result.map((s) => `${s.name} (${s.format})`)),
    'sprites differ from the jar listsprite render',
  );
  return result;
}

function readOpeniconic(plantuml: string): string[] {
  const names = readLines(readFileSync(join(plantuml, 'src/main/resources/openiconic/all.txt'), 'utf8'));
  const missing = names.filter((name) => !Object.hasOwn(RAW_GLYPHS, name));
  check(missing.length === 0, `all.txt names missing from RAW_GLYPHS: ${missing.join(', ')}`);
  return names;
}

function readStdlibCatalog(stdlibSvg: string): StdlibCatalogEntry[] {
  const manifest = JSON.parse(readFileSync(join(REPO, 'assets/stdlib.manifest.json'), 'utf8')) as StdlibManifest;
  const catalog = stdlibCatalog(manifest);
  // `addInfoVersion` (java:325-328): name / Version / Delivered by / " " per folder; the
  // jar writes the blank line as `&#160;`, so blank texts are dropped before comparing.
  const printed = catalog.flatMap((e) => [e.name, `Version ${e.version}`, `Delivered by ${e.source}`]);
  const texts = svgTexts(stdlibSvg).filter((text) => text.trim() !== '');
  check(JSON.stringify(texts) === JSON.stringify(printed), 'stdlib differs from the jar render');
  return catalog;
}

function readData(plantuml: string, svgs: ReadonlyMap<string, string>): GeneratedData {
  const donorsJava = readFileSync(
    join(plantuml, 'src/main/java/net/sourceforge/plantuml/donors/PSystemDonors.java'),
    'utf8',
  );
  const skinparameterNames = svgTexts(svgs.get('skinparameters')!);
  check(
    JSON.stringify(skinparameterNames) === JSON.stringify(javaTreeSetOrder(skinparameterNames)),
    'skinparameters render is not a TreeSet listing',
  );
  return {
    openiconicAll: readOpeniconic(plantuml),
    archimateSpriteNames: readArchimate(plantuml, svgs.get('listsprite')!),
    skinparameterNames,
    donors: decodeDonors(extractJavaStringConstant(donorsJava, 'DONORS')),
    stdlibCatalog: readStdlibCatalog(svgs.get('stdlib')!),
  };
}

function writeDedicationAssets(svgs: ReadonlyMap<string, string>): Record<string, DedicationImage> {
  mkdirSync(join(REPO, OUTPUT.dedicationAssets), { recursive: true });
  const images: Record<string, DedicationImage> = {};
  for (const [resource, sentence] of DEDICATION_SENTENCES) {
    const embedded = svgImage(svgs.get(`dedication-${resource}`)!);
    const bytes = Buffer.from(embedded.png, 'base64');
    check(
      JSON.stringify(pngSize(bytes)) === JSON.stringify({ width: embedded.width, height: embedded.height }),
      resource,
    );
    writeFileSync(join(REPO, OUTPUT.dedicationAssets, `${resource}.png`), bytes);
    const sha256 = createHash('sha256').update(bytes).digest('hex');
    images[sentence] = {
      resource,
      assetKey: `dedication:${resource}.png`,
      width: embedded.width,
      height: embedded.height,
      sha256,
    };
  }
  return images;
}

async function main(argv: readonly string[]): Promise<void> {
  const flag = argv.indexOf('--plantuml');
  const plantuml = flag === -1 ? join(homedir(), 'git/plantuml') : argv[flag + 1]!;
  const svgs = renderOracles(oraclePumls());
  const modules = await emitModules(readData(plantuml, svgs));
  const charlie = svgImage(svgs.get('charlie')!);
  check(
    JSON.stringify(pngSize(Buffer.from(charlie.png, 'base64'))) ===
      JSON.stringify({ width: charlie.width, height: charlie.height }),
    'charlie',
  );
  const extra = [await emitCharlieModule(charlie), await emitDedicationModule(writeDedicationAssets(svgs))];
  for (const [path, text] of [...modules, ...extra]) {
    mkdirSync(dirname(join(REPO, path)), { recursive: true });
    writeFileSync(join(REPO, path), text);
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  main(process.argv.slice(2)).catch((error: unknown) => {
    console.error(error);
    process.exitCode = 1;
  });
}

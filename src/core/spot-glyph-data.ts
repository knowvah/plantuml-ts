const NUMBER_RE = new RegExp('-?\\d+(?:\\.\\d+)?', 'g');

/**
 * The captured outline of `letter` at `fontSize`, translated so the glyph
 * centres on (`cx`, `cy`) and scaled by `k` about its captured centre (the
 * jar's `SvgGraphics#format` scales every emitted number), or `undefined`
 * when that (size, letter) was never captured. Coordinates alternate x, y in
 * every command this letter set emits (`M`/`L`/`Q`/`Z`).
 */
export function spotGlyphPath(letter: string, fontSize: number, cx: number, cy: number, k = 1): string | undefined {
  const table = fontSize === DEFAULT_SPOT_FONT_SIZE ? SPOT_GLYPHS_17 : SPOT_GLYPHS_BY_SIZE[fontSize];
  const glyph = table !== undefined && Object.hasOwn(table, letter) ? table[letter] : undefined;
  if (glyph === undefined) return undefined;
  const dx = cx - glyph.refCx * k;
  const dy = cy - glyph.refCy * k;
  let axis = 0;
  return glyph.d.replace(NUMBER_RE, (tok) => {
    const shifted = Number(tok) * k + (axis === 0 ? dx : dy);
    axis = 1 - axis;
    return formatDecimal(shifted, DEFAULT_SVG_DECIMALS);
  });
}

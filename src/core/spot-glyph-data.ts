/**
 * Captured glyph outlines of the circled-character SPOT letter -- the
 * `<path>` the jar draws inside a `CircledCharacter` badge.
 *
 * `Display#createStereotype` builds a `CircledCharacter` for a spotted
 * stereotype (`Display.java:673-678`); its `drawU` fills the ellipse, then
 * draws `UCenteredCharacter(c, font)` (`CircledCharacter.java:63-70`), which
 * `DriverCenteredCharacterSvg#draw` (`:56-81`) renders as the glyph's
 * `TextLayout#getOutline` path -- a real system-font outline, centred by
 * `UnusedSpace` (`:72-76`). Its `<text>` shortcut (`:64-69`) fires only for
 * `FileFormat.SVG_DETERMINISTIC`, a format the oracle renders never select
 * (`-DPLANTUML_DETERMINISTIC_TEXT=true` swaps only the `StringBounder`), so a
 * letter's outline cannot be computed here: it is scraped from a cached jar
 * SVG and translated to the badge centre.
 *
 * The size-17 table (`circledCharacterFontSize`'s default) is lifted from
 * `diagrams/class/class-badge-glyph-data.ts#BADGE_GLYPH_D` (captures and
 * cross-checks documented there), which still owns its own copy: class and
 * activity are untouched by sdd2-T7d, and a later cleanup may re-point them
 * here. Not lifted: `W`, which that file records as a size-12 scrape
 * mislabelled as size 17. Added from sequence goldens:
 *   - `U`, size 17: `nimoxu-60-xale291` (`<< (U,#ADD1B2) >>`, ellipse
 *     `cx=104.45 cy=28`), stored at its own centre.
 *   - `C`, size 10: `fakova-98-suze610` (`skinparam CircledCharacterFontSize
 *     10`, ellipse `cx=26 cy=26 rx=9`), stored at its own centre.
 *
 * A (size, letter) with no capture has NO outline here ({@link spotGlyphPath}
 * answers `undefined`): a glyph from another size or letter would be a
 * fabricated shape, not the jar's.
 */

